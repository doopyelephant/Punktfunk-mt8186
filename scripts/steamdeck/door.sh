# shellcheck shell=bash
# Sourced by lib.sh: Reachable without logging in on a Deck build. The files every package ships
# from packaging/linux, laid out where SteamOS keeps them across its A/B updates: programs under
# /opt, units and rules in /etc on the atomic-update keep list, and the door's and the seats'
# state on /home, bind-mounted over their /var paths.
#
# Root runs only what door_install puts in $PF_OPT/libexec, root-owned. The door and the seats run
# the host and console in $PF_COPY, which is the owner's: a rebuild after an OS update refreshes it
# without sudo, and the door picks it up on its next restart. The supervisor links only glibc, so an
# OS update never needs it rebuilt.

PF_OPT=/opt/punktfunk
PF_COPY=$PF_OPT/host
# Valve's own home for /var paths too big for the 256 MB var partition (/var/lib/flatpak lives here).
PF_OFFLOAD=/home/.steamos/offload/var/lib

# The packaged paths in a file from packaging/linux, moved to where this install keeps them.
door_paths() {
    sed -e "s|/usr/libexec/punktfunk/|$PF_OPT/libexec/|g" \
        -e "s|/usr/bin/punktfunk-host|$PF_COPY/punktfunk-host|g" \
        -e "s|/usr/bin/punktfunk-web-server|$PF_COPY/punktfunk-web-server|g" \
        -e "s|/usr/share/punktfunk/headless|$PF_OPT/share/headless|g" "$@"
}

# /var/lib/$1 bind-mounted from /home. Seat homes and the shared games folder live below these, and
# SteamOS's /var sync skips another file system.
door_offload() {
    local dir=/var/lib/$1 unit
    unit=$(systemd-escape -p --suffix=mount "$dir")
    # Made once: the door helper and tmpfiles own its mode and owner from then on.
    sudo test -d "$PF_OFFLOAD/$1" || sudo install -d -m 0711 "$PF_OFFLOAD/$1"
    if ! mountpoint -q "$dir" && [ -n "$(sudo ls -A "$dir" 2>/dev/null)" ]; then
        sudo cp -a "$dir/." "$PF_OFFLOAD/$1/"
    fi
    sudo tee "/etc/systemd/system/$unit" >/dev/null <<EOF
# Generated by scripts/steamdeck/door.sh — $dir on /home, where SteamOS updates keep it.
[Unit]
Description=punktfunk: $dir on /home
RequiresMountsFor=/home

[Mount]
What=$PF_OFFLOAD/$1
Where=$dir
Type=none
Options=bind

[Install]
WantedBy=local-fs.target
EOF
    sudo systemctl daemon-reload
    sudo systemctl enable --now "$unit" >/dev/null
}

# The host and console the door and seats run, from this build. Each file is swapped in whole, so a
# running door keeps its program until it restarts. No sudo.
door_copy() {
    local bun=$HOME/.bun/bin/bun web=$PF_COPY/web
    [ -x "$bun" ] || bun=$HOME/.local/lib/punktfunk-scripting/bun
    install -m 0755 "$BIN" "$PF_COPY/punktfunk-host.new"
    mv -f "$PF_COPY/punktfunk-host.new" "$PF_COPY/punktfunk-host"
    if [ -x "$WORKER" ]; then
        install -m 0755 "$WORKER" "$PF_COPY/punktfunk-encode-worker.new"
        mv -f "$PF_COPY/punktfunk-encode-worker.new" "$PF_COPY/punktfunk-encode-worker"
    fi
    install -m 0755 "$bun" "$PF_COPY/bun.new"
    mv -f "$PF_COPY/bun.new" "$PF_COPY/bun"
    rm -rf "$web.new" "$web.old"
    cp -R "$SRC/web/.output" "$web.new"
    chmod -R a+rX "$web.new"
    [ ! -d "$web" ] || mv "$web" "$web.old"
    mv "$web.new" "$web"
    rm -rf "$web.old"
    cat >"$PF_COPY/punktfunk-web-server.new" <<EOF
#!/bin/sh
# Generated by scripts/steamdeck/door.sh — the door's console on its own copy of bun.
exec $PF_COPY/bun $web/server/index.mjs "\$@"
EOF
    chmod 0755 "$PF_COPY/punktfunk-web-server.new"
    mv -f "$PF_COPY/punktfunk-web-server.new" "$PF_COPY/punktfunk-web-server"
    # The door runs as another user, so it reads the checkout's branch, its channel, from here.
    if [ -f "$SRC/.git/HEAD" ]; then cp "$SRC/.git/HEAD" "$PF_COPY/source-head"; fi
}

# Everything the door needs, from this checkout. Needs sudo; re-run by every install.sh and
# update.sh that has it, so a changed file reaches an installed Deck.
door_install() {
    local libexec=$PF_OPT/libexec share=$PF_OPT/share f
    if [ ! -x "$TARGET_DIR/release/punktfunk-seats" ] || [ ! -f "$SRC/web/.output/server/index.mjs" ]; then
        warn "Reachable without logging in needs the seat supervisor and the web console build — skipped"
        return 0
    fi
    door_offload punktfunk
    door_offload punktfunk-seats
    sudo install -d -m 0755 "$PF_OPT" "$libexec" "$share/headless" "$share/applications"
    sudo install -m 0755 "$TARGET_DIR/release/punktfunk-seats" "$libexec/punktfunk-seats"
    for f in door-helper seat-session seat-reap; do
        door_paths "$SRC/packaging/linux/$f" | sudo install -m 0755 /dev/stdin "$libexec/$f"
    done
    for f in kde-authorized punktfunk-sink.conf; do
        sudo install -m 0644 "$SRC/scripts/headless/$f" "$share/headless/$f"
    done
    # A seat's KWin grants capture to the host its .desktop names; XDG_DATA_DIRS below finds it.
    sudo rm -f "$share/applications/io.unom.Punktfunk.Host.desktop"  # the CamelCase name
    sed "s|^Exec=.*|Exec=$PF_COPY/punktfunk-host|" "$SRC/packaging/linux/io.unom.punktfunk.host.desktop" \
        | sudo install -m 0644 /dev/stdin "$share/applications/io.unom.punktfunk.host.desktop"
    for f in punktfunk-seats.service punktfunk-seat@.service punktfunk-door.service \
        punktfunk-web-door.service punktfunk-door-on@.service punktfunk-door-off@.service; do
        door_paths "$SRC/packaging/linux/$f" | sudo install -m 0644 /dev/stdin "/etc/systemd/system/$f"
    done
    sudo install -Dm 0644 "$SRC/packaging/linux/punktfunk-seats-user.conf" \
        /etc/systemd/system/user@.service.d/50-punktfunk-seats.conf
    sudo install -d -m 0755 /etc/systemd/system/punktfunk-seat@.service.d
    sudo tee /etc/systemd/system/punktfunk-seat@.service.d/50-steamos.conf >/dev/null <<EOF
# Generated by scripts/steamdeck/door.sh — the host's KWin grant, under /opt on SteamOS.
[Service]
Environment=XDG_DATA_DIRS=$share:/usr/local/share:/usr/share:/var/lib/flatpak/exports/share
EOF
    sudo install -Dm 0644 "$SRC/packaging/linux/49-punktfunk-door.rules" /etc/polkit-1/rules.d/49-punktfunk-door.rules
    door_paths "$SRC/packaging/linux/65-punktfunk-seats.rules" \
        | sudo install -Dm 0644 /dev/stdin /etc/udev/rules.d/65-punktfunk-seats.rules
    sudo install -Dm 0644 "$SRC/packaging/linux/punktfunk-seats.tmpfiles" /etc/tmpfiles.d/punktfunk-seats.conf
    sudo systemd-tmpfiles --create /etc/tmpfiles.d/punktfunk-seats.conf
    sudo udevadm control --reload-rules >/dev/null 2>&1 || true
    sudo systemctl daemon-reload
    sudo install -d -m 0755 -o "$(id -u)" -g "$(id -g)" "$PF_COPY"
    door_copy
    printf '%s\n' "$PF_BUILD_VERSION" | sudo install -m 0644 /dev/stdin "$PF_OPT/version"
    # Running this script is the opt-in to the switch, as on the packaged boxes' usermod step.
    if ensure_group punktfunk-update && ! id -nG "$USER" | grep -qw punktfunk-update; then
        sudo usermod -aG punktfunk-update "$USER"
        NEED_RELOGIN=1
        warn "added $USER to 'punktfunk-update', which may start the switch — it applies after a reboot"
    fi
    # The door's units run in this group and don't start without it.
    ensure_group punktfunk-door || warn "couldn't create the 'punktfunk-door' group — the door won't start"
    sudo systemctl try-restart punktfunk-seats.service punktfunk-door.service punktfunk-web-door.service
    ok "Reachable without logging in: ready to turn on under Profiles in the console"
}

# The no-sudo half: a rebuild of the version the door already runs, which is what the post-OS-update
# check makes. Another version waits for door_install, so the door and its supervisor never differ.
door_refresh() {
    [ -w "$PF_COPY" ] || return 0
    if [ "$(cat "$PF_OPT/version" 2>/dev/null || true)" != "$PF_BUILD_VERSION" ]; then
        warn "Reachable without logging in stays on its version until update.sh runs with your password"
        return 0
    fi
    door_copy
    ok "Reachable without logging in: refreshed"
}

# The user's own console stands down while the door is on, as the packaged unit does. The
# owner's contract exists from before linger starts the console at boot; the door's console doesn't.
door_yield_web_unit() {
    local unit=$UNITS/punktfunk-web.service line
    [ -f "$unit" ] || return 0
    for line in 'ConditionPathExists=!/run/punktfunk-web-door' 'ConditionPathExists=!/run/punktfunk/seats/%u.env'; do
        grep -qxF "$line" "$unit" || sed -i "s|^\[Unit\]\$|[Unit]\n$line|" "$unit"
    done
}
